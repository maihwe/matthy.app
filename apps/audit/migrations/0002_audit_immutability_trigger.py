"""Audit immutability, enforced in the database (FR-AUD-003, 03 §12.1).

**This migration is hand-written, and it is the only one in the project that
should be.** Its content is DDL that Django's autodetector cannot express: a
plpgsql function and a ``BEFORE UPDATE OR DELETE`` trigger. Everything else is
generated by ``makemigrations`` and must stay that way, because a hand-written
migration that disagrees with the model state fails ``makemigrations --check``
(gate 5) and, worse, fails it *after* review.

``0001_initial`` is created by ``makemigrations``, not by this file — and **this
file must be deleted first, before any ``makemigrations`` will run.**

That is not a warning to file away; it is the current state. ``makemigrations``
builds the migration graph before it does anything else, and this file's
``dependencies`` entry names ``audit.0001_initial``, which does not exist yet. So
the first ``makemigrations`` after this file lands fails with a
``NodeNotFoundError`` naming this migration. That failure is correct, it is loud,
and it points at the file to remove. The order is:

1. Delete this file.
2. ``python manage.py makemigrations accounts audit`` — writes ``0001_initial``
   for both apps, generated and therefore identical to what gate 5 expects.
3. ``python manage.py makemigrations audit --empty -n audit_immutability_trigger``
   — writes this file back with the correct name and the correct dependency.
4. Paste the ``operations`` list below into the result, unchanged.

The file is committed in this "before" state on purpose, rather than held back
until step 3 can run: the SQL below is the part that cannot be regenerated from
the models, and losing it to a lost scratch file is a worse risk than a
migration graph that is knowingly one step from complete.

**Why a trigger rather than a model-level guard.** ``AuditLog.save()`` and
``AuditLog.delete()`` already raise, but they are not the control:
``QuerySet.update()`` and ``QuerySet.delete()`` never call them, and neither
does a cascade from another table. 03 §12.1 says an audit record "must not be
*casually* editable or deletable" — *casually* is the operative word, and a
trigger is what makes the answer "not without deliberately dropping a trigger
first", which is no longer casual. The Python guards exist alongside it so that
the ordinary mistake produces a legible ``RuntimeError`` instead of a psycopg
error surfacing from inside an unrelated test.

**The error code is chosen, not defaulted.** ``restrict_violation`` (SQLSTATE
23001) is in class 23, so psycopg maps it to ``psycopg.errors.RestrictViolation``
— a subclass of ``IntegrityError`` — and Django wraps it as
``django.db.utils.IntegrityError``. A refused write therefore looks exactly like
every other constraint violation to application code and to tests, rather than
arriving as an opaque ``DatabaseError`` that callers would have to special-case.

**TRUNCATE is not covered, and cannot be.** ``TRUNCATE`` does not fire row-level
triggers. The application's database role must therefore not own
``audit_logs``; if it does, immutability is advisory. That is a deployment
requirement, not a code one, and it is recorded in 12.

**Retention is not implemented, and this trigger will block it.** SEC-AUD-006
sets audit retention from a regulatory requirement that 14 has not yet answered,
so no retention window exists. When one does, a plain
``DELETE FROM audit_logs WHERE occurred_at < ...`` will be refused here — by
design. The mechanism then has to be either table partitioning with partition
drops, or a migration that disables the trigger inside a controlled transaction.
Both are deliberate acts. That is the point.
"""

from __future__ import annotations

from django.db import migrations

# 03 §12.1 names both objects. They are reproduced exactly, because a trigger
# named differently from the document is a trigger nobody finds with `\d`.
FUNCTION_NAME = "raise_audit_immutable"
TRIGGER_NAME = "trg_audit_logs_immutable"
TABLE_NAME = "audit_logs"

CREATE_FUNCTION = f"""
CREATE OR REPLACE FUNCTION {FUNCTION_NAME}()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    RAISE EXCEPTION
        'audit_logs is append-only (FR-AUD-003); % is not permitted', TG_OP
        USING ERRCODE = 'restrict_violation',
              HINT = 'Write a new audit entry describing the correction.';
END;
$$;
"""

CREATE_TRIGGER = f"""
CREATE TRIGGER {TRIGGER_NAME}
BEFORE UPDATE OR DELETE ON {TABLE_NAME}
FOR EACH ROW EXECUTE FUNCTION {FUNCTION_NAME}();
"""

# Ordered teardown: the trigger depends on the function, so the function cannot
# go first.
DROP_TRIGGER = f"DROP TRIGGER IF EXISTS {TRIGGER_NAME} ON {TABLE_NAME};"
DROP_FUNCTION = f"DROP FUNCTION IF EXISTS {FUNCTION_NAME}();"


class Migration(migrations.Migration):
    dependencies = [
        # Resolved to the app's first migration by ``makemigrations``. Stated
        # explicitly rather than as ``__first__`` so that the dependency is
        # readable in the file and in ``showmigrations``.
        ("audit", "0001_initial"),
    ]

    operations = [
        migrations.RunSQL(
            sql=CREATE_FUNCTION,
            reverse_sql=DROP_FUNCTION,
        ),
        migrations.RunSQL(
            sql=CREATE_TRIGGER,
            reverse_sql=DROP_TRIGGER,
        ),
    ]
